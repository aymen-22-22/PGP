const DICTS: Record<MailLang, Record<string, string>> = { en, fr, ar };
const LOCALES: Record<MailLang, string> = { en: 'en-GB', fr: 'fr-FR', ar: 'ar-DZ-u-nu-latn' };

export function translator(lang: MailLang): Translate {
  const dict = DICTS[lang];
  return (key, params = {}) => {
    const n = params.n;
    const plural = typeof n === 'number' ? `${key}_${n === 1 ? 'one' : 'other'}` : null;
    const text = (plural && (dict[plural] ?? en[plural])) ?? dict[key] ?? en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
  };
}

export const formatDateTime = (lang: MailLang, d: Date): string =>
  d.toLocaleString(LOCALES[lang], { dateStyle: 'medium', timeStyle: 'short' });
export const formatDate = (lang: MailLang, d: Date): string => d.toLocaleDateString(LOCALES[lang], { dateStyle: 'medium' });
